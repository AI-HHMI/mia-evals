# `..` from `leaderboard/<task>/README.md` is `leaderboard/`, so docs are two levels up -- one more
# than the old single table at `leaderboard/README.md` needed.
TASK_HEADER = """<!-- GENERATED FILE -- do not edit by hand.
     Regenerate with `mia-evals leaderboard --task {task}`, or verify with `--check`.
     Rows come from ./records/; edit a record, not this table. -->

# {task}

The artifact/checkpoint/view links below point to locations on the Janelia cluster and will only work on the Janelia network."""

VIEWS_LINE = "\n**Views:** [neuroglancer views for every row below]({url})"

VIEWS_HTML = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>{task}: views</title>
<style>
 body {{ font: 15px/1.45 system-ui, sans-serif; margin: 2em auto; max-width: 60em; color: #111; }}
 h1, h2 {{ font-weight: 600; }} h2 {{ margin-top: 2em; font-family: ui-monospace, monospace; }}
 table {{ border-collapse: collapse; }} td, th {{ padding: .3em .9em; border-bottom: 1px solid #ddd;
 text-align: left; }} a {{ color: #1a5fb4; }} p.note {{ color: #555; }}
</style></head><body>
<h1>{task}: views</h1>
<p>One neuroglancer view per volume and row of the leaderboard, in fileglancer's hosted viewer
(Janelia network). <b>overlay</b>: the raw image with the scored labelling drawn over it and the
ground truth loaded but hidden until its tab is clicked. <b>side by side</b>: two panes sharing
position and zoom, ground truth over the raw on the left, the labelling on the right. Layers are
placed by the files' own OME-Zarr metadata. Where the row's post-processed labelling was kept
(<b>scored</b>), that is what is shown, with the producer's raw output as a hidden
<i>unfiltered</i> layer; otherwise the producer's output before the size filter. Rows in
leaderboard order.</p>
<p class="note">The links come from each row's record, where <code>mia-evals score</code> stores
them using the scorer's own fileglancer key file. A volume marked <i>missing</i> has no view links
in its record: score it on a machine whose keys cover its artifacts, or run
<code>mia-evals leaderboard --refresh-views</code> where they do. Generated by
<code>mia-evals leaderboard --task {task}</code>.</p>
{body}
</body></html>
"""

INDEX_HEADER = """<!-- GENERATED FILE -- do not edit by hand.
     Regenerate with `mia-evals leaderboard`, or verify with `--check`. -->

# Leaderboards"""


def _report_keys(metric_name: str) -> tuple[str, ...]:
    """The secondary columns a metric asks for, or none if it is not registered here.

    Looked up rather than stored in the record so that adding a column to a metric changes every
    table on the next render, without rewriting records that were correct when written.
    """
    try:
        import components  # noqa: F401  (populates the registry)
        from metrics.registry import MetricRegistry

        return tuple(MetricRegistry.get(metric_name).report_keys)
    except (ImportError, KeyError):
        return ()


def _region_key(submission: Submission) -> str:
    """A short label for the extent scored, used to group rows that may be compared."""
    volumes = submission.region.get("volumes") or {}
    if not volumes:
        return "unspecified"
    parts = []
    for name in sorted(volumes):
        entry = volumes[name]
        shape = entry.get("shape")
        whole = entry.get("whole_region")
        extent = "x".join(str(int(s)) for s in shape) if shape else "?"
        parts.append(f"{name} {extent}{'' if whole else ' (sub-region)'}")
    return "; ".join(parts)


#: The truth kinds as they were named before the 2026-09-14 rename, so records written under the
#: old names read as the same route and do not force a column that shows a spelling difference.
LEGACY_TRUTH_KINDS = {"labels": "instances", "sibling_artifact": "instances_resampled"}


def _truth_kind(submission: Submission) -> str:
    """How the record's task read its ground truth; `—` for a task with no such setting."""
    kwargs = (submission.config.get("task") or {}).get("kwargs") or {}
    kind = str(kwargs.get("truth_kind", "—"))
    return LEGACY_TRUTH_KINDS.get(kind, kind)


def _cell(value: Any) -> str:
    if isinstance(value, float):
        return f"{value:.4f}"
    return "—" if value is None else str(value)


_VIEWS_LINE_URL = re.compile(r"^\*\*Views:\*\* \[[^\]]*\]\((\S+)\)", re.MULTILINE)


def views_link(root: Path, task_name: str) -> str | None:
    """The data-link URL of this task's HTML views page, or None if there is none.

    The URL carries the share's key, and the table it goes into is committed. That is accepted:
    the links only resolve for people with Janelia access, and a table that names its views is
    worth more than one that hides them. The key *file* stays untracked all the same -- so on a
    machine without it, the link already in the committed table is kept rather than dropped,
    which is what lets anyone re-render or `--check` the table and get the same text.
    """
    target = views_directory(root / SHARE_KEYS)
    if target is not None:
        page = Path(str(target).replace("{task}", task_name)) / f"{task_name}.html"
        if page.is_file():
            return share_url(page, load_share_keys(root / SHARE_KEYS))
    existing = readme_path(root, task_name)
    if existing.is_file():
        match = _VIEWS_LINE_URL.search(existing.read_text())
        if match:
            return match.group(1)
    return None


def render_task(task_name: str, submissions: list[Submission],
                views: str | None = None) -> str:
    """One task's page: a table per region it was scored over, linking its views page if any."""
    header = TASK_HEADER.format(task=task_name)
    if not submissions:
        return header + "\n\nNo records yet.\n"

    out = [header]
    if views:
        out.append(VIEWS_LINE.format(url=views))
    shares = default_shares()
    truths = {_truth_kind(s) for s in submissions}
    show_truth = len(truths) > 1
    by_region: dict[str, list[Submission]] = {}
    for submission in submissions:
        by_region.setdefault(_region_key(submission), []).append(submission)

    if len(by_region) > 1:
        out.append(
            "> Scored over different regions, so the groups below are **not** comparable with "
            "one another. Several of these metrics change with extent.\n"
        )

    for region in sorted(by_region):
        group = by_region[region]
        ranking = group[0].ranking
        metric, key = ranking.get("metric", "?"), ranking.get("key", "?")
        higher = bool(ranking.get("higher_is_better", True))
        group.sort(key=lambda s: s.ranking.get("value", 0.0), reverse=higher)

        # Columns in the order the *metrics* declare, not discovery order. A union over
        # sorted keys gave the alphabetically-first six, which for an instance task meant a
        # constant setting and a misleading count while the diagnostic split/merge terms were
        # dropped. `report_keys` lives on the metric because it knows which of its outputs are
        # diagnostic; anything a metric does not name stays out of the table and remains in
        # the record.
        extra: list[str] = []
        for submission in group:
            for name in sorted(submission.scores):
                for inner in _report_keys(name):
                    column = f"{name}.{inner}"
                    if (column != f"{metric}.{key}"
                            and column not in extra
                            and inner in submission.scores[name]):
                        extra.append(column)

        out.append(f"\n**Region:** {region}\n")
        direction = "higher is better" if higher else "lower is better"
        columns = ["#", "model", "links", f"{metric}.{key} ({direction})", "postprocess",
                   *(["truth"] if show_truth else []), *extra[:6]]
        out.append("| " + " | ".join(columns) + " |")
        out.append("|" + "|".join(["---"] * len(columns)) + "|")
        for position, submission in enumerate(group, start=1):
            cells = [
                str(position),
                submission.identifier(),
                link_cell(
                    [("artifacts", artifact_directory(submission.producer)),
                     ("checkpoint",
                      checkpoint_directory(submission.producer, submission.provenance))],
                    shares,
                ),
                _cell(submission.ranking.get("value")),
                str(submission.postprocess.get("describe", "—")),
                *([_truth_kind(submission)] if show_truth else []),
            ]
            for column in extra[:6]:
                name, _, inner = column.partition(".")
                cells.append(_cell(submission.scores.get(name, {}).get(inner)))
            out.append("| " + " | ".join(cells) + " |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def render_views(task_name: str, submissions: list[Submission]) -> str | None:
    """One HTML page: per row, per volume, the overlay and side-by-side links from the record.

    Rendered from records alone. A volume without links in its record is marked missing, so the
    page can be hosted by one person and still show every contributor's rows as they arrive.
    """
    from html import escape

    if not submissions:
        return None
    ordered = sorted(
        submissions, key=lambda s: s.ranking.get("value", 0.0),
        reverse=bool(submissions[0].ranking.get("higher_is_better", True)),
    )
    parts = []
    for position, submission in enumerate(ordered, start=1):
        name = escape(submission.identifier())
        parts.append(f"<h2>{position}. {name}</h2>")
        volumes = sorted(
            {str(v.get("name")) for v in (submission.config.get("volumes") or [])
             if isinstance(v, dict)}
            | set(submission.views)
        )
        if not volumes:
            parts.append("<p class=\"note\">no volumes recorded for this row</p>")
            continue
        rows = []
        for volume in volumes:
            view = submission.views.get(volume)
            if not view:
                rows.append(f"<tr><td>{escape(volume)}</td>"
                            "<td colspan=\"3\"><i>missing</i></td></tr>")
                continue
            rows.append(
                f"<tr><td>{escape(volume)}</td>"
                f"<td><a href=\"{escape(str(view['overlay']))}\">overlay</a></td>"
                f"<td><a href=\"{escape(str(view['side_by_side']))}\">side by side</a></td>"
                f"<td>{escape(str(view.get('shows', '')))}</td></tr>"
            )
        parts.append("<table><tr><th>volume</th><th></th><th></th><th>shows</th></tr>"
                     + "".join(rows) + "</table>")
    return VIEWS_HTML.format(task=escape(task_name), body="\n".join(parts))


def refresh_views(root: Path, task_name: str | None = None) -> list[Path]:
    """Recompute every record's view links from this machine's key file; the files rewritten.

    For records scored before links were stored, or on a machine whose keys did not cover their
    artifacts. Only records that gain or change links are rewritten, and nothing is removed: a
    record's links are kept when this machine's keys cannot see its artifacts.
    """
    keys = load_share_keys(root / SHARE_KEYS)
    if not keys:
        return []
    rewritten = []
    for name in ([task_name] if task_name else task_names(root)):
        for path in sorted(records_dir(root, name).glob("*.json")):
            submission = load_record(path)
            views = record_views(submission.producer, submission.postprocess, submission.config,
                                 keys, submission.identifier())
            if views and views != submission.views:
                submission.views = views
                path.write_text(json.dumps(asdict(submission), indent=2, sort_keys=False) + "\n")
                rewritten.append(path)
    return rewritten


def write_views(root: Path, task_name: str, submissions: list[Submission]) -> str | None:
    """The task's HTML views page, written into the data-link directory; its served URL, or
    None when `<root>/fileglancer_shares.json` names no shares or no `views_dir`."""
    key_file = root / SHARE_KEYS
    keys, target = load_share_keys(key_file), views_directory(key_file)
    page = render_views(task_name, submissions)
    if page is None or target is None:
        return None
    # `{task}` in `views_dir` puts each task's page in that task's own directory
    # (/nrs/.../mia-evals/<task>/views), the per-task layout the artifact tree uses.
    target = Path(str(target).replace("{task}", task_name))
    target.mkdir(parents=True, exist_ok=True)
    path = target / f"{task_name}.html"
    path.write_text(page)
    return share_url(path, keys)


def render_index(root: Path) -> str:
    """The directory listing at `leaderboard/README.md`: which tasks exist, and how big.

    Deliberately holds no scores. A shared page that ranked anything would recreate the thing the
    split was for -- two tasks under one heading, read as one comparison.
    """
    out = [INDEX_HEADER, "\n| task | entries | table |", "| --- | --- | --- |"]
    names = task_names(root)
    for name in names:
        count = len(load_task(root, name))
        out.append(f"| `{name}` | {count} | [{name}/README.md]({name}/README.md) |")
    if not names:
        out.append("| _none yet_ |  |  |")
    return "\n".join(out).rstrip() + "\n"


def write_task(root: Path, task_name: str) -> Path:
    """Render one task's table in place, leaving every other task's file untouched.

    The views page is written first, into the data-link directory and never into the repository,
    so that the table can link to it. Its content is not part of `check`; the link to it is.
    """
    output = readme_path(root, task_name)
    output.parent.mkdir(parents=True, exist_ok=True)
    submissions = load_task(root, task_name)
    write_views(root, task_name, submissions)
    output.write_text(render_task(task_name, submissions, views_link(root, task_name)))
    return output


def write_index(root: Path) -> Path:
    output = root / "README.md"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render_index(root))
    return output


def write(root: Path, task_name: str | None = None) -> list[Path]:
    """Rebuild one task's table, or every task's plus the index.

    The index is rewritten even for a single task, because a new task's first record creates a
    directory the index does not yet list, and a stale index is the one drift `--check` on a single
    task cannot see.
    """
    written = [write_task(root, task_name)] if task_name else [
        write_task(root, name) for name in task_names(root)
    ]
    return [*written, write_index(root)]


def check(root: Path, task_name: str | None = None) -> list[Path]:
    """Files whose rendered content differs from what is on disk. Empty means up to date."""
    names = [task_name] if task_name else task_names(root)
    stale = []
    for name in names:
        output = readme_path(root, name)
        expected = render_task(name, load_task(root, name), views_link(root, name))
        if not output.is_file() or output.read_text() != expected:
            stale.append(output)
    index = root / "README.md"
    if not index.is_file() or index.read_text() != render_index(root):
        stale.append(index)
    return stale
